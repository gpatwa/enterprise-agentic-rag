"""Generate and check the tool catalogue document and its lock (ADS-060).

`python -m app.agent_tools.catalogue --write` regenerates both files; a test requires them to match the code, so a schema
change cannot land without regenerating the lock and (by convention) bumping `TOOL_CATALOG_VERSION`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from packages.platform_contracts.agent_tools import TOOL_CATALOG_VERSION, TOOLS, catalog, catalog_digest

HERE = Path(__file__).resolve().parent
LOCK = HERE / "catalogue.lock.json"
DOC = HERE.parents[3] / "docs" / "execution" / "enterprise-analytics" / "agent-tools-catalogue.md"


def lock_payload() -> dict:
    return {
        "catalog_version": TOOL_CATALOG_VERSION,
        "schema_digest": catalog_digest(),
        "tools": [t.name for t in TOOLS],
    }


def render_doc() -> str:
    lines = [
        f"# Agent tool catalogue (`{TOOL_CATALOG_VERSION}`)",
        "",
        "Generated by `python -m app.agent_tools.catalogue --write` from `packages/platform_contracts/agent_tools.py`; "
        "do not edit by hand. Every tool calls the same governed service as the REST API, so authorization, "
        "idempotency, and audit are identical. Results carry stable codes and never SQL, rows, or policy values.",
        "",
        f"Schema digest: `{catalog_digest()}`",
        "",
        "| Tool | Effect | Idempotency key | Human only |",
        "|---|---|:---:|:---:|",
    ]
    for tool in TOOLS:
        lines.append(
            f"| `{tool.name}` | {tool.effect} | {'required' if tool.requires_idempotency_key else '-'} "
            f"| {'yes' if tool.human_only else '-'} |"
        )
    for entry in catalog():
        schema = entry["arguments"]
        required = set(schema.get("required", []))
        lines += [
            "",
            f"## `{entry['name']}`",
            "",
            f"**{entry['title']}.** {entry['description']}",
            "",
            "| Argument | Type | Required | Constraints |",
            "|---|---|:---:|---|",
        ]
        for name, prop in schema["properties"].items():
            kind = prop.get("type") or "|".join(str(item.get("type")) for item in prop.get("anyOf", []))
            limits = (
                ", ".join(f"{key}={prop[key]}" for key in ("minLength", "maxLength", "pattern") if key in prop)
                or ", ".join(f"one of {prop['enum']}" for _ in [0] if "enum" in prop)
                or "-"
            )
            lines.append(f"| `{name}` | {kind} | {'yes' if name in required else '-'} | {limits} |")
        lines.append("")
        lines.append("Unknown arguments are rejected.")
    lines += [
        "",
        "## Errors",
        "",
        "`unknown_tool` (404), `invalid_tool_call` / `invalid_arguments` (422), `human_required` (403), plus the service codes "
        "of the REST API (`purpose_not_authorized`, `run_not_found`, `idempotency_key_reused`, `review_not_permitted`, ...). "
        "`analytics.evidence` adds `run_not_terminal` and `evidence_unavailable` (409) and `evidence_not_configured` (503).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if "--write" in argv:
        LOCK.write_text(json.dumps(lock_payload(), indent=2) + "\n")
        DOC.write_text(render_doc())
        return 0
    return (
        0 if LOCK.read_text() == json.dumps(lock_payload(), indent=2) + "\n" and DOC.read_text() == render_doc() else 1
    )


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
